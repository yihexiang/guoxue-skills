def _radical_of(ch: str) -> str:
    """取字符部首：优先显式标定（CHAR_RADICAL），其次常见偏旁表，再次合体字子串兜底。"""
    if ch in CHAR_RADICAL:
        return CHAR_RADICAL[ch]
    if ch in _RADICAL_MAP:
        return _RADICAL_MAP[ch]
    for rad in ("氵", "艹", "忄", "扌", "犭", "纟", "礻", "衤", "阝", "辶", "彡",
                "日", "月", "木", "火", "土", "金", "水", "宀", "亻", "女", "玉", "钅",
                "山", "雨", "禾", "米", "豆", "田", "心", "口", "车", "马"):
        if rad in ch:
            return rad
    return ch[0] if ch else ch


