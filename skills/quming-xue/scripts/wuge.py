# 三、三才配置（天/人/地 数理五行 → 生克等级）
# --------------------------------------------------------------------------
_WX = {"木", "火", "土", "金", "水"}
# 五行生克：相生 木→火→土→金→水→木；相克 木→土→水→火→金→木。
_SHENG = {"木": "火", "火": "土", "土": "金", "金": "水", "水": "木"}
_KE = {"木": "土", "土": "水", "水": "火", "火": "金", "金": "木"}


def _ke(a, b) -> bool:
    """a 是否克 b"""
    return _KE.get(a) == b


def sancai(tiange: int, renge: int, dige: int) -> dict:
    """三才配置：天/人/地 的五行 + 等级。

    等级规则（通行的五行生克判定，来源：美名腾《三才配置吉凶表》所据原理）：
      大吉：天→人→地 顺生（天生命格被层层生扶）
      中吉：地→人→天 逆生（根基生扶核心）
      吉  ：天=人=地 比和（专注稳定）
      凶  ：天克人 或 人克地（阻力、基础不稳）
      大凶：人克天 或 地克人（核心受挫、家庭失和）
    注：具体门派表对个别组合有细化（如木木金=凶多吉少），本引擎按生克原理给主等级，
        并在 note 中声明「传统表有细化，本引擎据生克原理判定」。
    """
    t, r, d = num_wuxing(tiange), num_wuxing(renge), num_wuxing(dige)
    if _SHENG[t] == r and _SHENG[r] == d:
        grade, gnote = "大吉", "天→人→地 顺生"
    elif _SHENG[d] == r and _SHENG[r] == t:
        grade, gnote = "中吉", "地→人→天 逆生"
    elif t == r == d:
        grade, gnote = "吉", "三才比和"
    elif _ke(t, r) or _ke(r, d):
        grade, gnote = "凶", ("天克人" if _ke(t, r) else "人克地")
    elif _ke(r, t) or _ke(d, r):
        grade, gnote = "大凶", ("人克天" if _ke(r, t) else "地克人")
    else:
        grade, gnote = "吉", "无冲克"
    return {"天格五行": t, "人格五行": r, "地格五行": d, "等级": grade, "说明": gnote}


