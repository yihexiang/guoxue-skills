def _resolve_zodiac(z) -> str:
    z = str(z).strip()
    if z in SHENGXIAO:
        return z
    return _SHENGXIAO_ALIAS.get(z, z)


def shengxiao_check(zodiac: str, name_chars: list[str]) -> dict:
    """检查名字中各字部首是否犯生肖宜忌。

    返回 {生肖, 宜用字:[], 忌用字:[]}。部首判定用首字符查常见偏旁表。
    注：部首→生肖宜忌是经验性规则，本函数只做「部首是否落入宜/忌集合」的机械匹配。
    """
    z = _resolve_zodiac(zodiac)
    rule = SHENGXIAO.get(z)
    if rule is None:
        return {"生肖": z, "错误": "未知生肖", "宜用字": [], "忌用字": []}
    good, bad = [], []
    for ch in name_chars:
        rad = _radical_of(ch)
        rad = _RADICAL_NORMALIZE.get(rad, rad)
        if rad in rule["宜"]:
            good.append((ch, rad))
        elif rad in rule["忌"]:
            bad.append((ch, rad))
    return {"生肖": z, "宜用字": good, "忌用字": bad}


